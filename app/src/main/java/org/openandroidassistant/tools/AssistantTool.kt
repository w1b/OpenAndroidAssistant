package org.openandroidassistant.tools

import android.content.Context
import org.openandroidassistant.orchestrator.HandleEntry
import org.openandroidassistant.orchestrator.HandleTable
import org.openandroidassistant.proto.AssistantSettings

/**
 * One tool in the catalog. Tools do the fuzzy, ranked work (search, matching); actions act on
 * result ids from earlier calls.
 */
interface AssistantTool {
  val metadata: ToolMetadata

  /** The model-facing definition. Fixed for a conversation once it starts. */
  fun schema(env: ToolEnvironment): ToolSchema

  /** Runs the validated call. Only invoked after approval and the lock check have passed. */
  suspend fun execute(call: ValidatedCall, context: ToolContext): ToolOutcome

  /**
   * What the user approves, generated from the actual call and the resolved objects, never from
   * anything the model said. Required for any tool whose approval level can be
   * above [ApprovalLevel.NONE], which is every tool.
   */
  fun approvalContent(call: ValidatedCall, context: ToolContext): ApprovalContent
}

/** What tool definitions may depend on at conversation start. */
data class ToolEnvironment(
  /** A location is available (setting on, permission granted or home set). */
  val locationAvailable: Boolean,
  /** Google Maps is installed, so directions can start navigation (OsmAnd and Organic Maps only plan the route). */
  val googleMapsInstalled: Boolean,
)

/** A call that passed schema validation and result-id resolution. */
data class ValidatedCall(
  val toolId: String,
  /** Coerced args keyed by param name (enum values validated, ints as Long, bools as Boolean). */
  val args: Map<String, Any?>,
  /** Resolved entries for every result-id param. */
  val handles: Map<String, HandleEntry>,
  /** Resolved entries for every result-id list param. */
  val handleLists: Map<String, List<HandleEntry>> = emptyMap(),
) {
  fun stringArg(name: String): String? = (args[name] as? String)?.trim()?.takeIf { it.isNotEmpty() }

  fun longArg(name: String): Long? =
    when (val v = args[name]) {
      is Long -> v
      is Double -> v.toLong()
      is Int -> v.toLong()
      else -> null
    }

  fun boolArg(name: String): Boolean? = args[name] as? Boolean

  fun handleArg(name: String): HandleEntry? = handles[name]
}

/** App services available to tool implementations. */
class ToolContext(
  val appContext: Context,
  val settings: AssistantSettings,
  val handleTable: HandleTable,
  /** Resolves the user's location for tools that need it. */
  val location: LocationProvider,
)

/** The single location setting, resolved for tools. Coordinates never reach the model. */
interface LocationProvider {
  /** Null when location is off, permission is missing, or no home is set. */
  suspend fun current(): UserLocation?
}

data class UserLocation(
  val latitude: Double,
  val longitude: Double,
  /** Human label such as "Austin, Texas", when known. */
  val label: String? = null,
)

/** The approval prompt and card, both generated by the app from the resolved call. */
data class ApprovalContent(
  /** e.g. "Send Harold Finch: I'm gonna be late?" */
  val spokenPrompt: String,
  val card: ApprovalCard,
)

data class ApprovalCard(
  /** Action label, e.g. "Send message". */
  val title: String,
  /** The resolved target, e.g. "Harold Finch". */
  val target: String,
  /** The payload being approved, e.g. the message text. Empty for target-only actions. */
  val body: String = "",
)
